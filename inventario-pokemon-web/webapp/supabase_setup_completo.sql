create table if not exists compras (
  id text primary key,
  date date,
  seller text,
  description text,
  card_count integer default 0,
  total_cost numeric default 0,
  notes text,
  created_at timestamptz default now()
);

create table if not exists items (
  id text primary key,
  set_code text,
  num integer,
  name text,
  lang text,
  variant text,
  cond text,
  qty integer default 0,
  cost numeric default 0,
  price numeric default 0,
  purchase_id text references compras(id) on delete set null,
  loc text,
  platform text,
  status text default 'En stock',
  listed boolean default false,
  created_at timestamptz default now()
);

create table if not exists ventas (
  id text primary key,
  date date,
  platform text,
  buyer text,
  commission numeric default 0,
  shipping numeric default 0,
  notes text,
  created_at timestamptz default now()
);

create table if not exists venta_items (
  id text primary key,
  venta_id text references ventas(id) on delete cascade,
  item_id text references items(id) on delete set null,
  item_label text,
  purchase_id text references compras(id) on delete set null,
  qty integer default 1,
  price_unit numeric default 0,
  cost_unit numeric default 0,
  created_at timestamptz default now()
);

create index if not exists idx_items_purchase on items(purchase_id);
create index if not exists idx_items_set on items(set_code);
create index if not exists idx_venta_items_venta on venta_items(venta_id);
create index if not exists idx_venta_items_item on venta_items(item_id);
create index if not exists idx_venta_items_purchase on venta_items(purchase_id);

